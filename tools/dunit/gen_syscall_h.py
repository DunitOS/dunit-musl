#!/usr/bin/env python3
# Regenerate arch/x86_64/bits/syscall.h.in for the Dunit OS target.
#
# musl references hundreds of SYS_* syscall names unconditionally, so every name
# must stay DEFINED or the libc will not compile. But Dunit's kernel speaks its
# own small native syscall set (see dunit-os abi/syscalls.abi), NOT Linux's — and
# the Linux numbers collide dangerously with Dunit's (Linux write=1 is Dunit
# Fork!). So this script rewrites the numbers:
#
#   * A syscall whose Linux name maps to a Dunit syscall with matching semantics
#     gets the Dunit number (DUNIT_MAP below). This table IS the documentation of
#     what the port actually supports at the raw-syscall layer.
#   * Every other name gets a distinct sentinel (>= SENTINEL_BASE). The Dunit
#     kernel does not know these numbers and returns -ENOSYS (M6.1: a documented
#     ENOSYS, never a silent fake success). Functions that rely on them fail
#     cleanly until their themed commit (fs:/vm:/thread:/signal:) lands.
#
# The script reads only the NAMES from the existing file, so it is idempotent and
# survives upstream rebases (new upstream syscalls simply start life as ENOSYS).
#
# Run from the fork root:   python3 tools/dunit/gen_syscall_h.py
#
import re
import sys
from pathlib import Path

# Linux __NR_<name>  ->  Dunit syscall number (abi/syscalls.abi in dunit-os).
# Only semantics-verified, argument-compatible calls belong here. Dunit mirrors
# POSIX fd/count/pid conventions, so these are 1:1 in register layout.
DUNIT_MAP = {
    "read": 3,            # Read(fd, buf, len)      -> Dunit Read
    "write": 4,           # Write(fd, buf, len)     -> Dunit Write
    "close": 6,           # Close(fd)               -> Dunit Close
    # open is NOT a plain number map: the kernel takes Open(path_ptr, path_len,
    # dunit_flags) while POSIX passes open(path_ptr, flags, mode) with Linux flag
    # VALUES. The number lets src/dunit/open.c reach the kernel; that adapter
    # computes the length and translates the flag bits (see the file).
    "open": 5,            # -> Dunit Open (via src/dunit/open.c adapter)
    "getpid": 17,         # getpid()                -> Dunit GetPid
    "sched_yield": 24,    # sched_yield()           -> Dunit Yield
    # Working directory. getcwd(buf,size) matches Dunit GetCwd(buf,size) (returns
    # the length, writes the NUL-terminated path), so it maps directly. chdir is
    # reshaped to (ptr,len) in src/unistd/chdir.c.
    "getcwd": 22,         # getcwd(buf, size)       -> Dunit GetCwd
    "chdir": 23,          # -> Dunit Chdir (via src/unistd/chdir.c, ptr+len)
    # Anonymous memory for malloc. Dunit's prot bits (R=1/W=2/X=4) and the
    # MAP_PRIVATE(0x2)|MAP_ANONYMOUS(0x20) flag values match Linux exactly, and
    # the kernel reads only (addr,len,prot,flags) — fd/offset are ignored, so
    # file-backed mmap (no MAP_ANONYMOUS) is rejected EINVAL rather than faked.
    "mmap": 7,            # mmap(addr,len,prot,flags,-1,0) -> Dunit Mmap (anon only)
    "munmap": 34,         # munmap(addr,len)        -> Dunit Munmap
    "mprotect": 35,       # mprotect(addr,len,prot) -> Dunit Mprotect
    # Seek. x86_64 lseek(fd, offset, whence) maps 1:1 onto Dunit Seek, which sets
    # the open handle's offset (whence 0/1/2 = SET/CUR/END) and returns the new
    # absolute offset. No _llseek on x86_64, so src/unistd/lseek.c calls this
    # directly; stdio fseek/ftell ride on it.
    "lseek": 80,          # lseek(fd, offset, whence) -> Dunit Seek
    # File management. All path-based Dunit calls take (ptr,len), so the wrappers
    # (unlink/rmdir/mkdir/rename, in src/unistd + src/stat + src/stdio) are
    # reshaped to pass strlen. fsync(fd) matches 1:1.
    "unlink": 68,         # -> Dunit Unlink (also rmdir; remove_at handles dirs)
    "rmdir": 77,          # -> Dunit Rmdir (removes an empty dir)
    "mkdir": 70,          # -> Dunit Mkdir (mode dropped)
    "rename": 69,         # -> Dunit Rename (old_ptr,old_len,new_ptr,new_len)
    "fsync": 72,          # fsync(fd)               -> Dunit Fsync
    # Thread vs process termination: musl ends a THREAD with SYS_exit and the
    # whole PROCESS with SYS_exit_group. Dunit splits these too, so exit ->
    # ThreadExit (just this thread) and exit_group -> Exit (the process).
    "exit": 31,           # -> Dunit ThreadExit
    "exit_group": 0,      # -> Dunit Exit (process)
    # set_tid_address registers the clear-child-tid word AND returns the tid.
    # The kernel zeroes that word + futex-wakes it on thread exit, which musl
    # relies on (Linux CLONE_CHILD_CLEARTID) to release __thread_list_lock.
    "set_tid_address": 75,  # -> Dunit SetTidAddress
}

SENTINEL_BASE = 0x44440000  # 'DD..' — clearly not a Dunit syscall; kernel -> ENOSYS

HEADER = """\
/*
 * Dunit OS syscall numbers for x86_64-dunit. GENERATED by
 * tools/dunit/gen_syscall_h.py from the Dunit ABI mapping — do not hand-edit.
 *
 * Names mapped to a real Dunit syscall carry its number (see the generator's
 * DUNIT_MAP, which documents the supported raw-syscall surface). Every other
 * name is a sentinel the kernel answers with -ENOSYS (M6.1: documented, never a
 * silent fake). The full list of names is kept so musl still compiles.
 */
"""


def main() -> int:
    root = Path(__file__).resolve().parents[2]
    path = root / "arch" / "x86_64" / "bits" / "syscall.h.in"
    names = []
    for line in path.read_text().splitlines():
        m = re.match(r"\s*#define\s+__NR_(\S+)\s+", line)
        if m:
            names.append(m.group(1))
    if not names:
        print(f"error: no __NR_ names found in {path}", file=sys.stderr)
        return 1

    out = [HEADER]
    sentinel = SENTINEL_BASE
    width = max(len(n) for n in names) + 1
    n_mapped = 0
    for name in names:
        if name in DUNIT_MAP:
            val = DUNIT_MAP[name]
            n_mapped += 1
        else:
            val = sentinel
            sentinel += 1
        out.append(f"#define __NR_{name.ljust(width)}{val}")
    out.append("")
    path.write_text("\n".join(out))
    print(f"wrote {path}: {len(names)} syscalls, {n_mapped} mapped to Dunit, "
          f"{len(names) - n_mapped} -> ENOSYS sentinel")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
