#!/bin/sh
# Regenerate DELTA.md: the table of this fork's changes vs the pinned upstream
# musl base (M6.2 "upstream delta table"). Keeps the OS-specific diff visible and
# reviewable. Run from the fork root:   tools/dunit/gen-delta.sh
set -eu

root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
cd "$root"

# Pinned base commit, read from UPSTREAM.md (single source of truth).
base=$(grep -oE '[0-9a-f]{40}' UPSTREAM.md | head -n1)
if [ -z "$base" ]; then
	echo "gen-delta: no 40-char base commit found in UPSTREAM.md" >&2
	exit 1
fi
if ! git merge-base --is-ancestor "$base" HEAD 2>/dev/null; then
	echo "gen-delta: base $base is not an ancestor of HEAD (fetch upstream?)" >&2
	exit 1
fi

short=$(git rev-parse --short "$base")
added=$(git diff --diff-filter=A --name-only "$base" HEAD | sort)
modified=$(git diff --diff-filter=M --name-only "$base" HEAD | sort)
deleted=$(git diff --diff-filter=D --name-only "$base" HEAD | sort)

{
	echo "# Dunit delta vs upstream musl"
	echo
	echo "GENERATED by \`tools/dunit/gen-delta.sh\` — the OS-specific change set this"
	echo "fork carries on top of the pinned upstream base (\`$short\`, see UPSTREAM.md)."
	echo "Keep it small and confined to the Dunit adaptation layer; never reformat"
	echo "upstream files (M6.1/M6.2)."
	echo
	echo "## Added (Dunit-only files)"
	echo
	echo '```'
	echo "${added:-"(none)"}"
	echo '```'
	echo
	echo "## Modified upstream files"
	echo
	echo '```'
	git diff --stat "$base" HEAD -- $(echo "$modified") 2>/dev/null | sed '$d' || true
	echo '```'
	if [ -n "$deleted" ]; then
		echo
		echo "## Deleted upstream files (should be empty — exclude from build instead)"
		echo
		echo '```'
		echo "$deleted"
		echo '```'
	fi
	echo
	echo "## Summary"
	echo
	echo '```'
	git diff --shortstat "$base" HEAD
	echo '```'
} > DELTA.md

echo "wrote DELTA.md (base $short)"
