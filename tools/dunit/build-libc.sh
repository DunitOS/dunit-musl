#!/bin/sh
# Build the Dunit OS musl port: a static libc.a + crt objects for the
# x86_64-dunit target, installed into a sysroot.
#
# The CPU is still x86_64 and the low-level syscall instruction/register
# convention already matches Dunit (see PORTING.md), so the host x86_64 C
# compiler is the cross compiler here — no separate x86_64-dunit-gcc is needed
# to produce the freestanding, static libc.a. What makes the result a *Dunit*
# libc rather than a Linux one is the syscall-number remap and the Dunit crt/
# adaptation layer carried in this fork, NOT the compiler.
#
# Usage:
#   tools/dunit/build-libc.sh [SYSROOT_DIR]
#
# SYSROOT_DIR defaults to ./build/dunit-sysroot (created if absent). Override
# the toolchain with CC=, AR=, RANLIB= in the environment. The build happens
# out-of-tree so the fork's working tree stays clean.
set -eu

srcdir=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
sysroot=${1:-"$(pwd)/build/dunit-sysroot"}
builddir=${DUNIT_MUSL_BUILDDIR:-"$(pwd)/build/dunit-musl-build"}
CC=${CC:-cc}
AR=${AR:-ar}
RANLIB=${RANLIB:-ranlib}

echo "dunit-musl: srcdir=$srcdir"
echo "dunit-musl: sysroot=$sysroot"
echo "dunit-musl: builddir=$builddir  CC=$CC"

rm -rf "$builddir"
mkdir -p "$builddir"
cd "$builddir"

"$srcdir/configure" \
	--target=x86_64-dunit \
	--disable-shared \
	--prefix="$sysroot" \
	CC="$CC" AR="$AR" RANLIB="$RANLIB"

make -j"$(nproc 2>/dev/null || echo 2)"
make install

# Install a convenience wrapper that compiles+links a static x86_64-dunit program
# with one command (the M6.4 cross-"toolchain"). It finds the sysroot relative to
# its own location, so the sysroot stays relocatable. Honors $CC (default cc).
# For -c/-S/-E/-print-* it only adds the Dunit headers; otherwise it also pulls
# in crt1/crti + libc.a + libgcc + crtn to produce an ET_EXEC at 0x400000.
mkdir -p "$sysroot/bin"
cat > "$sysroot/bin/dunit-cc" <<'WRAP'
#!/bin/sh
# Dunit static C compiler wrapper (x86_64-dunit). GENERATED by build-libc.sh.
set -e
SYSROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
CC=${CC:-cc}
HDRS="-nostdinc -isystem $SYSROOT/include"
BASE="-fno-pic -fno-stack-protector -fno-asynchronous-unwind-tables"
for a in "$@"; do
	case "$a" in
	-c|-S|-E|-print-*|-M|-MM)
		exec "$CC" $HDRS $BASE "$@" ;;
	esac
done
LIBGCC=$("$CC" -print-libgcc-file-name)
exec "$CC" $HDRS $BASE -static -no-pie -nostdlib -nostartfiles \
	"$SYSROOT/lib/crt1.o" "$SYSROOT/lib/crti.o" \
	"$@" \
	"$SYSROOT/lib/libc.a" "$LIBGCC" "$SYSROOT/lib/crtn.o"
WRAP
chmod +x "$sysroot/bin/dunit-cc"

# Prefixed toolchain command names (M6.4). x86_64-dunit-cc is the wrapper; ar and
# strip are the host tools (they already handle x86_64 archives/ELF).
ln -sf dunit-cc "$sysroot/bin/x86_64-dunit-cc"
for t in ar strip; do
	cat > "$sysroot/bin/x86_64-dunit-$t" <<W
#!/bin/sh
exec ${t} "\$@"
W
	chmod +x "$sysroot/bin/x86_64-dunit-$t"
done

# SDK manifest (M6.2/M6.4): ABI/libc versions, supported profile and license
# provenance, so any build records exactly what it links against.
base=$(grep -oE '[0-9a-f]{40}' "$srcdir/UPSTREAM.md" 2>/dev/null | head -n1)
mkdir -p "$sysroot/share/dunit-sdk"
cat > "$sysroot/share/dunit-sdk/manifest" <<MANIFEST
# Dunit SDK manifest (generated by build-libc.sh)
target        = x86_64-dunit
abi           = Dunit Userspace ABI v0
libc          = musl (fork), upstream base ${base:-unknown}
link          = static only (no dynamic/.so yet)
profile       = ISO C core; crt/errno/allocator/env; files+dirs+stat+cwd;
                buffered stdio; clock(monotonic)/sleep; pthread subset
unsupported   = signals, networking, dynamic linking (documented ENOSYS)
license       = MIT (musl COPYRIGHT); Dunit delta: see DELTA.md
MANIFEST

echo "dunit-musl: built x86_64-dunit libc into $sysroot"
ls -1 "$sysroot/lib/libc.a" "$sysroot/lib/crt1.o" "$sysroot/lib/crti.o" \
	"$sysroot/lib/crtn.o" "$sysroot/bin/dunit-cc" "$sysroot/bin/x86_64-dunit-cc" \
	"$sysroot/share/dunit-sdk/manifest"
